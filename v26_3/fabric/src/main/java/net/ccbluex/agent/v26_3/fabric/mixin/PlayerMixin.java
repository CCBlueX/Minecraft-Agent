package net.ccbluex.agent.v26_3.fabric.mixin;

import net.ccbluex.agent.v26_3.fabric.ClientHooks;
import net.minecraft.world.entity.player.Player;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/**
 * Safe walk: the ledge check sneaking makes, without sneaking.
 */
@Mixin(Player.class)
abstract class PlayerMixin {

    @Inject(method = "isStayingOnGroundSurface", at = @At("RETURN"), cancellable = true)
    private void agent$safeWalk(CallbackInfoReturnable<Boolean> info) {
        if (!info.getReturnValueZ() && ClientHooks.holdsAtLedges((Player) (Object) this)) {
            info.setReturnValue(true);
        }
    }

}
